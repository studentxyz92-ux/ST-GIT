"use client";

import { useState } from "react";
import { motion } from "framer-motion";
import type { AnalysisResult } from "@/lib/types";

interface ExportSectionProps {
  result: AnalysisResult;
  repoFullName: string;
}

export default function ExportSection({ result, repoFullName }: ExportSectionProps) {
  const [copied, setCopied] = useState(false);

  function exportAsJSON() {
    const data = {
      tool: "DevScore.ai",
      version: "0.1.0",
      timestamp: new Date().toISOString(),
      repository: repoFullName,
      analysis: result,
    };
    downloadFile(JSON.stringify(data, null, 2), "devscore-report.json", "application/json");
  }

  function exportAsMarkdown() {
    const md = generateMarkdown(result, repoFullName);
    downloadFile(md, "devscore-report.md", "text/markdown");
  }

  async function copyJSON() {
    const data = JSON.stringify({ repository: repoFullName, analysis: result }, null, 2);
    await navigator.clipboard.writeText(data);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  }

  return (
    <motion.div
      className="share-section"
      initial={{ opacity: 0, y: 20 }}
      animate={{ opacity: 1, y: 0 }}
      transition={{ delay: 0.3 }}
    >
      <div className="share-title">📥 Export Report</div>
      <div className="share-subtitle">Download or copy your analysis in various formats</div>
      <div className="share-buttons">
        <button className="share-btn share-btn-twitter" onClick={exportAsJSON} style={{ background: "var(--indigo)" }}>
          📄 Export JSON
        </button>
        <button className="share-btn share-btn-linkedin" onClick={exportAsMarkdown} style={{ background: "var(--emerald)" }}>
          📝 Export Markdown
        </button>
        <button className="share-btn share-btn-copy" onClick={copyJSON}>
          {copied ? "✅ Copied!" : "📋 Copy JSON"}
        </button>
      </div>
    </motion.div>
  );
}

function downloadFile(content: string, filename: string, mimeType: string) {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  a.click();
  URL.revokeObjectURL(url);
}

function generateMarkdown(result: AnalysisResult, repoFullName: string): string {
  const lines: string[] = [];
  lines.push(`# 📊 DevScore Report: ${repoFullName}`);
  lines.push("");
  lines.push(`**Overall Score**: ${result.overallScore}/10 — **${result.hiringReadiness}**`);
  lines.push("");
  lines.push(result.summary);
  lines.push("");
  lines.push("## 🏆 Sub-Scores");
  lines.push("| Category | Score |");
  lines.push("|----------|------:|");
  for (const sub of result.subScores) {
    lines.push(`| ${sub.icon} ${sub.name} | ${sub.score}/10 |`);
  }
  lines.push("");
  if (result.issues.length > 0) {
    lines.push("## ⚠️ Issues");
    for (const issue of result.issues) {
      const icon = issue.severity === "critical" ? "🔴" : issue.severity === "warning" ? "🟡" : "🔵";
      lines.push(`- ${icon} **${issue.title}**: ${issue.description}`);
    }
    lines.push("");
  }
  lines.push("## 💡 Suggestions");
  for (let i = 0; i < result.suggestions.length; i++) {
    lines.push(`${i + 1}. **${result.suggestions[i].title}**: ${result.suggestions[i].detail}`);
  }
  lines.push("");
  lines.push("## ✅ Strengths");
  for (const s of result.strengths) {
    lines.push(`- ${s}`);
  }
  lines.push("");
  lines.push("---");
  lines.push(`_Generated by DevScore.ai on ${new Date().toLocaleDateString()}_`);
  return lines.join("\n");
}
